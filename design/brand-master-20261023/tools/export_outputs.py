"""Exports vector PDFs of the master and the app's mark module from the master SVG files.

Run from the project root after build_master.py:
    python design/brand-master-20261023/tools/export_outputs.py
PDFs are drawn with matplotlib from the same path data (arcs sampled at 0.5 degree), so they are vector files.
The app module (studio/src/experience/brand/markArt.ts) embeds the master path data with source hashes.
"""
from __future__ import annotations

import hashlib
import re
import sys
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
from matplotlib.patches import PathPatch  # noqa: E402
from matplotlib.path import Path as MplPath  # noqa: E402

sys.path.insert(0, str(Path(__file__).resolve().parent))
from build_master import BASE, PALETTE, ROOT  # noqa: E402
from pathmark import parse_svg_path  # noqa: E402

APP_MODULE = ROOT / "studio/src/experience/brand/markArt.ts"


def read_svg(name):
    text = (BASE / f"master/{name}.svg").read_text(encoding="utf-8")
    vb = [float(v) for v in re.search(r'viewBox="([^"]+)"', text).group(1).split()]
    d = re.search(r' d="([^"]+)"', text).group(1)
    return text, vb, d


def pdf(name, fill, background=None):
    _, vb, d = read_svg(name)
    geom = parse_svg_path(d, arc_step_deg=0.5)
    verts, codes = [], []
    polys = list(geom.geoms) if geom.geom_type == "MultiPolygon" else [geom]
    for poly in polys:
        for ring in [poly.exterior] + list(poly.interiors):
            pts = list(ring.coords)
            verts += pts
            codes += [MplPath.MOVETO] + [MplPath.LINETO] * (len(pts) - 2) + [MplPath.CLOSEPOLY]
    w, h = vb[2], vb[3]
    fig = plt.figure(figsize=(w / 72, h / 72), dpi=72)
    ax = fig.add_axes([0, 0, 1, 1])
    ax.set_xlim(0, w)
    ax.set_ylim(h, 0)
    ax.axis("off")
    if background:
        fig.patch.set_facecolor(background)
    else:
        fig.patch.set_alpha(0)
    ax.add_patch(PathPatch(MplPath(verts, codes), facecolor=fill, edgecolor="none"))
    suffix = "-on-moss" if background else ""
    out = BASE / f"master/pdf/{name}{suffix}.pdf"
    out.parent.mkdir(exist_ok=True)
    fig.savefig(out, format="pdf", transparent=background is None, facecolor=fig.get_facecolor())
    plt.close(fig)
    return out


def app_module():
    entries = []
    for key, name in [("SYMBOL", "kairo-symbol"), ("SYMBOL_MICRO", "kairo-symbol-micro"), ("LOCKUP_HORIZONTAL", "kairo-lockup-horizontal"),
                      ("LOCKUP_HORIZONTAL_MICRO", "kairo-lockup-horizontal-micro")]:
        text, vb, d = read_svg(name)
        sha = hashlib.sha256((BASE / f"master/{name}.svg").read_bytes()).hexdigest()
        entries.append((key, name, vb, d, sha, parse_svg_path(d).bounds))
    lines = ["// Generated by design/brand-master-20261023/tools/export_outputs.py from the outlined master SVGs.",
             "// Do not edit by hand: change the master and re-export. Path units are reference pixels; viewBox includes clear space.",
             "/** `ink` is the drawn outline's bounding box inside the viewBox (x0, y0, x1, y1). */",
             "export type MarkArt = { viewBox: string; ink: readonly [number, number, number, number]; d: string; source: string; sha256: string };", ""]
    for key, name, vb, d, sha, ink in entries:
        lines.append(f"export const {key}: MarkArt = {{")
        lines.append(f"  viewBox: '{' '.join(f'{v:g}' for v in vb)}',")
        lines.append(f"  ink: [{', '.join(f'{v:.2f}' for v in ink)}],")
        lines.append(f"  d: '{d}',")
        lines.append(f"  source: 'design/brand-master-20261023/master/{name}.svg',")
        lines.append(f"  sha256: '{sha}',")
        lines.append("};")
        lines.append("")
    lines.append("/** Below this rendered symbol (ink) height only the micro mark keeps both strokes and the open counter (measured). */")
    lines.append("export const MICRO_BELOW_PX = 32;")
    lines.append("")
    lines.append("/** The horizontal lockup's symbol is 1.4 cap heights inside a 2.4 cap viewBox (0.5 cap padding each side). */")
    lines.append(f"export const LOCKUP_SYMBOL_SHARE = {1.4 / 2.4:.4f};")
    lines.append("")
    APP_MODULE.parent.mkdir(parents=True, exist_ok=True)
    APP_MODULE.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    return APP_MODULE


def main():
    outs = [pdf("kairo-symbol", PALETTE["moss"]), pdf("kairo-lockup-stacked", PALETTE["moss"]),
            pdf("kairo-lockup-horizontal", PALETTE["moss"]), pdf("kairo-lockup-stacked-chalk", PALETTE["chalk"], PALETTE["moss"]),
            pdf("kairo-symbol-graphite", PALETTE["graphite"])]
    outs.append(app_module())
    for o in outs:
        print(o.relative_to(ROOT), o.stat().st_size)


if __name__ == "__main__":
    main()
